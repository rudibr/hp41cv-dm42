def runs(mask, y0=0, x0=0):
    out = []
    for y in range(mask.shape[0]):
        row = mask[y]; x = 0
        while x < row.shape[0]:
            if row[x]:
                s = x
                while x < row.shape[0] and row[x]: x += 1
                out.append((y + y0, s + x0, x - s))
            else:
                x += 1
    return out

bg = background()
bg[:HDR, :] = False
bgr = runs(bg)

# annunciators: black text on the LCD
names = ["BAT", "USER", "G", "RAD", "SHIFT", "0", "1", "2", "3", "4", "PRGM", "ALPHA"]
f9 = font(9)
tmp = ImageDraw.Draw(Image.new("L", (10, 10)))
ann = []
x = 22
for t in names:
    w = int(tmp.textlength(t, font=f9)) + 1
    im = Image.new("L", (w + 2, 14), 255)
    dd = ImageDraw.Draw(im); dd.fontmode = "1"
    dd.text((0, 0), t, font=f9, fill=0)
    m = np.asarray(im) < 128
    ann.append((t, runs(m, 108, x)))
    x += tmp.textlength(t, font=f9) + (9 if t not in "01234" else 4)

